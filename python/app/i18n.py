def localized_languages() -> List[Tuple[str, str]]:
    """
    Returns subtitle/audio language choices localized in the currently active UI language!
    """
    cur_ui = I18N.lang
    result: List[Tuple[str, str]] = []
    for code, locale_map in LANGUAGE_NAMES_BY_LOCALE.items():
        disp = locale_map.get(cur_ui) or locale_map.get("en", code)
        result.append((code, disp))
    return result


def localized_lang_name(code: str) -> str:
    if not code:
        return ""
    base = (code or "").split("-")[0].lower()
    cur_ui = I18N.lang
    for c_key, locale_map in LANGUAGE_NAMES_BY_LOCALE.items():
        if c_key.lower() == code.lower() or c_key.split("-")[0].lower() == base:
            return locale_map.get(cur_ui) or locale_map.get("en", code)
    return code


def normalize_search_query(text: str) -> str:
    """
    Normalizes text across Arabic, Persian, Urdu, Latin, Cyrillic, Greek, and Bengali scripts
    for fast, forgiving search inside Drop Panels (`SearchCombo`).
    """
    if not text:
        return ""
    s = unicodedata.normalize("NFKD", text.strip().lower())
    # Strip combining marks (diacritics, tashkeel, accents)
    s = "".join(ch for ch in s if not unicodedata.combining(ch))
    # Unify Arabic/Persian/Urdu variants
    s = (
        s.replace("أ", "ا")
        .replace("إ", "ا")
        .replace("آ", "ا")
        .replace("ٱ", "ا")
        .replace("ة", "ه")
        .replace("ى", "ي")
        .replace("ی", "ي")
        .replace("ك", "ك")
        .replace("ک", "ك")
        .replace("ے", "ي")
    )
    return s


def format_localized_number(value: int | float, decimals: int = 0) -> str:
    """Formats numbers cleanly for the active UI language."""
    if decimals > 0:
        return f"{float(value):,.{decimals}f}"
    return f"{int(value):,}"


def format_localized_datetime(dt: datetime | None = None) -> str:
    """Formats date and time according to the active UI language."""
    target = dt or datetime.now()
    if I18N.is_rtl():
        return target.strftime("%Y/%m/%d — %I:%M %p")
    return target.strftime("%d %b %Y, %H:%M")


def smart_pad_index(index: int, total_count: int) -> str:
    width = max(2, len(str(max(1, total_count))))
    if total_count >= 100 and width < 3:
        width = 3
    return f"{max(1, index):0{width}d}"
