for _lang_code, _overrides in _EXTRA_LANG_OVERRIDES.items():
    _base = dict(_AR_DICT if _lang_code in RTL_UI_LANGS else _EN_DICT)
    if _lang_code in FULL_T_KEYS:
        _base.update(FULL_T_KEYS[_lang_code])
    _base.update(_overrides)
    TRANSLATIONS[_lang_code] = _base


class I18NManager:
    def __init__(self) -> None:
        self._lang: str = "ar"

    @property
    def lang(self) -> str:
        return self._lang

    def is_rtl(self) -> bool:
        return self._lang in RTL_UI_LANGS

    def set_language(self, lang: str) -> None:
        valid_codes = {code for code, _ in UI_LANGUAGES}
        self._lang = lang if lang in valid_codes else "ar"
        app = QApplication.instance()
        if app is not None:
            direction = Qt.RightToLeft if self.is_rtl() else Qt.LeftToRight
            app.setLayoutDirection(direction)

    def t(self, key: str, **kwargs: object) -> str:
        table = TRANSLATIONS.get(self._lang, TRANSLATIONS["en"])
        raw = table.get(key, TRANSLATIONS["en"].get(key, key))
        if kwargs:
            try:
                return raw.format(**kwargs)
            except Exception:
                return raw
        return raw


